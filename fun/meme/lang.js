// Current language
let currentLanguage = localStorage.getItem('memeCreatorLanguage') || 'en';

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    setLanguage(currentLanguage);
    updateLanguageSwitcher();
});

// Language switcher buttons
document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        const lang = btn.dataset.lang;
        setLanguage(lang);
        updateLanguageSwitcher();
        localStorage.setItem('memeCreatorLanguage', lang);
    });
});

// Set language function
function setLanguage(lang) {
    currentLanguage = lang;
    document.documentElement.lang = lang;
    
    // Update all elements with data-en and data-ne attributes
    document.querySelectorAll('[data-en][data-ne]').forEach(element => {
        const text = lang === 'en' ? element.dataset.en : element.dataset.ne;
        
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            const placeholderAttr = lang === 'en' ? 'data-placeholder-en' : 'data-placeholder-ne';
            if (element.hasAttribute(placeholderAttr)) {
                element.placeholder = element.getAttribute(placeholderAttr);
            }
        } else if (element.tagName === 'OPTION') {
            element.textContent = text;
        } else {
            element.textContent = text;
        }
    });
    
    // Update option elements
    document.querySelectorAll('option[data-en][data-ne]').forEach(option => {
        const text = lang === 'en' ? option.dataset.en : option.dataset.ne;
        option.textContent = text;
    });
    
    // Update text content for elements with only data attributes
    document.querySelectorAll('[data-en]:not([data-ne])').forEach(element => {
        if (lang === 'en') {
            element.textContent = element.dataset.en;
        }
    });
}

// Update language switcher button states
function updateLanguageSwitcher() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.dataset.lang === currentLanguage) {
            btn.classList.add('active');
        }
    });
}

// Get translated text
function t(key) {
    return translations[currentLanguage][key] || translations['en'][key] || key;
}
